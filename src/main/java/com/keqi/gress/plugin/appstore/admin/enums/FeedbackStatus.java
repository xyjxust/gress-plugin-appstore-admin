package com.keqi.gress.plugin.appstore.admin.enums;

/**
 * Feedback Status Enumeration
 */
public enum FeedbackStatus {
    /**
     * Newly submitted, not yet processed
     */
    OPEN,
    
    /**
     * Being processed
     */
    IN_PROGRESS,
    
    /**
     * Issue resolved
     */
    RESOLVED,
    
    /**
     * Feedback closed
     */
    CLOSED
}
